"""Portable application exporter. Run by the user; no Codex/Node runtime needed.

Python Decimal owns the computed values; native Excel formulas reproduce them.
Cached formula results allow previews before Excel recalculates on opening.
"""
from __future__ import annotations

from decimal import Decimal
from io import BytesIO
from pathlib import Path
import re

from .analysis import INPUTS
from .workbook_schema import column_name, table_layout

AMOUNT = '#,##0.00;(#,##0.00);"-"'


def export_xlsx(payload: dict, output: Path) -> Path:
    import xlsxwriter

    output=Path(output)
    if output.exists():
        raise ValueError('输出已存在，请换文件名以保留原审核记录。')
    dataset,analysis=payload['dataset'],payload['analysis']
    formal=payload['mode']=='formal'
    automatic=bool(payload.get('validation'))
    if formal and analysis['status'] not in ('approved','validated'):
        raise ValueError('未完成全表人工审核，禁止正式分析和图表。')
    if automatic:
        from .automatic import assert_validation
        from .models import Dataset,SystemValidation
        assert_validation(Dataset.model_validate(dataset),SystemValidation.model_validate(payload['validation']))
    from .models import Dataset
    model=Dataset.model_validate(dataset)
    for statement in model.statements: table_layout(statement)
    by_id={s.statement_id:s for s in model.statements}
    decisions={d['statement_id']:d for d in (payload.get('review') or {}).get('decisions',[])}
    corrections={(sid,c['row_id'],c['column_id']):c for sid,d in decisions.items() for c in d['corrections']}
    buffer=BytesIO()
    workbook=xlsxwriter.Workbook(buffer,{'strings_to_formulas':False,'strings_to_urls':False})
    workbook.set_calc_mode('auto')
    workbook.set_properties({'title':'Annual report financial analysis','comments':'Generated by the financial analysis Agent application.'})
    fmt={
        'text':workbook.add_format({'font_name':'Arial','font_size':10,'valign':'vcenter'}),
        'wrap':workbook.add_format({'font_name':'Arial','font_size':10,'text_wrap':True,'valign':'vcenter'}),
        'title':workbook.add_format({'font_name':'Arial','font_size':16,'bold':True,'font_color':'#203B58'}),
        'header':workbook.add_format({'font_name':'Arial','font_size':10,'bold':True,'font_color':'white','bg_color':'#203B58','text_wrap':True,'valign':'vcenter'}),
        'source':workbook.add_format({'font_name':'Arial','font_size':10,'font_color':'#0000B8','num_format':AMOUNT}),
        'input':workbook.add_format({'font_name':'Arial','font_size':10,'bg_color':'#FFF3D6','locked':False,'text_wrap':True}),
        'override':workbook.add_format({'font_name':'Arial','font_size':10,'font_color':'#0000B8','bg_color':'#FFF3D6','locked':False,'num_format':AMOUNT}),
        'amount':workbook.add_format({'font_name':'Arial','font_size':10,'num_format':AMOUNT}),
        'linked':workbook.add_format({'font_name':'Arial','font_size':10,'font_color':'#008040','num_format':AMOUNT}),
        'percent':workbook.add_format({'font_name':'Arial','font_size':10,'num_format':'0.0%'}),
        'multiple':workbook.add_format({'font_name':'Arial','font_size':10,'num_format':'0.00"x"'}),
    }
    provenance_sheet='系统校验' if automatic else '审核'
    sheets={name:workbook.add_worksheet(name) for name in
            ['总分析',provenance_sheet,'分析计算',*[f'{s.report_year}_{s.kind}' for s in model.statements],'方法与口径']}
    for sh in sheets.values():
        sh.hide_gridlines(2); sh.set_default_row(23); sh.set_column('A:A',32,fmt['text'])
        sh.set_column('B:Z',23,fmt['text']); sh.freeze_panes(8,1)
    overview,review_sheet,build,method=[sheets[n] for n in ('总分析',provenance_sheet,'分析计算','方法与口径')]
    def write(sh,row,col,value,style='text'):
        if value is None: sh.write_blank(row,col,None,fmt[style])
        elif isinstance(value,(Decimal,int,float)) and not isinstance(value,bool): sh.write_number(row,col,float(value),fmt[style])
        else: sh.write_string(row,col,str(value),fmt[style])
    def title(sh,text): write(sh,1,0,text,'title'); sh.set_row(1,29)
    def header(sh,row,values):
        sh.set_row(row,31)
        for col,item in enumerate(values): write(sh,row,col,item,'header')
    def formula(sh,row,col,expression,cached,style='amount'):
        value=float(Decimal(str(cached))) if cached is not None and not isinstance(cached,str) else cached
        sh.write_formula(row,col,expression,fmt[style],value if value is not None else 'n.a.')
    for statement in model.statements:
        sh=sheets[f'{statement.report_year}_{statement.kind}']; layout=table_layout(statement)
        title(sh,f"{statement.report_year} "+{'IS':'合并利润表','BS':'合并资产负债表','CF':'合并现金流量表'}[statement.kind])
        write(sh,3,0,f'来源：{statement.file_name}；PDF 物理页：'+','.join(map(str,statement.pdf_pages)))
        write(sh,4,0,f'原单位：{statement.raw_unit}；空白不等于零。')
        write(sh,5,0,'系统校验通过；未经人工财务复核。' if automatic else '已人工确认；保留原始来源与修正记录。' if formal else '待人工确认：核对原 PDF 后填写“审核”页。')
        write(sh,6,0,'原 PDF 标签如已裁切则保留原样；修正填黄色栏，MISSING 表示缺失；不要改动原始列。')
        headers=['原始项目 / Item','附注',*[c.raw_header for c in statement.columns],
                 'PDF 页','标准指标','行标识',*[c.raw_header+' 修正' for c in statement.columns],'修正理由']
        header(sh,7,headers); sh.set_column(0,0,65,fmt['wrap']); sh.set_column(1,1,10)
        sh.set_column(layout.page,layout.page,9); sh.set_column(layout.metric,layout.metric,24)
        sh.set_column(layout.identity,layout.identity,28); sh.set_column(layout.reason,layout.reason,38,fmt['wrap'])
        for row_index,row in enumerate(statement.rows,8):
            write(sh,row_index,0,row.raw_label,'wrap'); write(sh,row_index,1,row.note)
            sh.set_row(row_index,max(24,14*((len(row.raw_label)+45)//46)))
            for i,value in enumerate(row.values):
                write(sh,row_index,layout.originals[i],value,'source')
                correction=corrections.get((statement.statement_id,row.row_id,statement.columns[i].column_id))
                override=correction['corrected'] if correction else None
                write(sh,row_index,layout.overrides[i],('MISSING' if override is None else Decimal(override)) if correction else None,'source' if formal else 'override')
            write(sh,row_index,layout.page,row.pdf_page); write(sh,row_index,layout.metric,row.canonical_metric or '')
            write(sh,row_index,layout.identity,row.row_id)
            reasons=list(dict.fromkeys(c['reason'] for key,c in corrections.items() if key[:2]==(statement.statement_id,row.row_id)))
            write(sh,row_index,layout.reason,'；'.join(reasons),'wrap' if formal else 'input')
        sh.protect('',{'select_locked_cells':True,'select_unlocked_cells':True})

    title(review_sheet,'系统校验记录' if automatic else '报表审核')
    write(review_sheet,3,0,f'{model.company_id}；{len(model.statements)} 张主表。')
    write(review_sheet,4,0,'系统检查原页、来源身份、单位和可适用勾稽；本次没有人工批准。' if automatic else 'C 列填 approved / rejected，D 列填审核人；有比较数差异时 E 列填 as_reported。')
    write(review_sheet,5,0,'比较差异按 as_reported 保留各年本年主列；缺失或不唯一的指标不自动补值。' if automatic else '逐表黄色修正栏与理由栏独立保存原始数值；另存审核副本后运行 finalize。')
    header(review_sheet,7,['年度','报表','校验状态' if automatic else '审核决定','校验方式' if automatic else '审核人','差异处理','校验说明' if automatic else '审核备注','报表标识','来源摘要'])
    review_sheet.set_column('A:B',10); review_sheet.set_column('F:F',55); review_sheet.set_column('G:H',30)
    for index,statement in enumerate(model.statements,8):
        decision=decisions.get(statement.statement_id,{})
        conflict=any(statement.statement_id in (c['current_statement_id'],c['comparison_statement_id']) for c in model.conflicts)
        passed=sum(c['status']=='pass' for c in statement.checks)
        note=f'自动勾稽 {passed}/{len(statement.checks)} 通过。' if statement.checks else '无适用的自动勾稽。'
        if conflict: note+='存在比较栏差异。'
        values=[statement.report_year,statement.kind,decision.get('decision','pending'),decision.get('reviewer',''),
                decision.get('conflict_resolution',''),decision.get('note',note),statement.statement_id,payload['statement_digests'][statement.statement_id]]
        if automatic:
            values=[statement.report_year,statement.kind,'validated','系统规则与原页复核','as_reported',note+' 未经人工复核。',statement.statement_id,payload['statement_digests'][statement.statement_id]]
        review_sheet.set_row(index,35)
        for col,item in enumerate(values): write(review_sheet,index,col,item,'input' if not formal and 2<=col<=5 else 'wrap')
        if not formal:
            review_sheet.data_validation(index,2,index,2,{'validate':'list','source':['pending','approved','rejected']})
            review_sheet.data_validation(index,4,index,4,{'validate':'list','source':['as_reported']})
    review_sheet.protect('')

    years=analysis['years']; inputs=analysis['inputs']; recipes=[r for r in analysis['results'] if r['year']==years[0]]
    input_rows={metric:i+8 for i,metric in enumerate(INPUTS)}
    result_start=len(INPUTS)+11; result_rows={r['name']:result_start+i for i,r in enumerate(recipes)}
    title(build,'历史分析计算'); write(build,3,0,'金额统一为报告原币种基本单位；使用系统校验的原始输入。' if automatic else '金额统一为报告原币种基本单位；只使用人工批准的输入。')
    write(build,4,0,'公式结果缓存由 Python Decimal 计算；Excel 打开后自动复算。')
    header(build,7,['系统校验输入' if automatic else '已批准输入',*years])
    for metric,row in input_rows.items():
        write(build,row,0,INPUTS[metric][0])
        for i,year in enumerate(years,1):
            item=inputs[str(year)][metric]
            if not formal or item['value'] is None:
                write(build,row,i,'待审核' if not formal else 'n.a.'); continue
            source=item['source']; statement=by_id[source['statement_id']]; layout=table_layout(statement)
            ri=next(j for j,r in enumerate(statement.rows,9) if r.row_id==source['row_id']); ci=source['column']
            prefix=f"'{statement.report_year}_{statement.kind}'!"
            original_ref=prefix+column_name(layout.originals[ci])+str(ri)
            override_ref=prefix+column_name(layout.overrides[ci])+str(ri)
            original=statement.rows[ri-9].values[ci]
            correction=corrections.get((statement.statement_id,source['row_id'],statement.columns[ci].column_id))
            original_check=f'ISBLANK({original_ref})' if original is None else f'AND(ISNUMBER({original_ref}),{original_ref}={original})'
            override_check=f'AND(ISNUMBER({override_ref}),{override_ref}={correction["corrected"]})' if correction else f'ISBLANK({override_ref})'
            ref=override_ref if correction else original_ref
            invalid_label='需重新校验' if automatic else '需重新审核'
            expression=f'=IF(AND({original_check},{override_check}),{ref}*{source["scale"]}*{source.get("sign",1)},"{invalid_label}")'
            formula(build,row,i,expression,float(Decimal(item['value'])),'linked')
    header(build,result_start-1,['历史指标',*years])
    results={(r['year'],r['name']):r for r in analysis['results']}
    for recipe in recipes:
        row=result_rows[recipe['name']]; write(build,row,0,recipe['name'])
        for i,year in enumerate(years,1):
            result=results[year,recipe['name']]
            if not formal: write(build,row,i,'待审核'); continue
            names=sorted(set(re.findall(r'[a-z_]+',recipe['expression'])))
            refs={name:f'{column_name(i)}{input_rows[name]+1}' for name in names}
            expression=re.sub(r'[a-z_]+',lambda m:refs[m[0]],recipe['expression'])
            conditions=[f'COUNT({",".join(refs.values())})={len(refs)}',*[f'{refs[n]}>0' for n in recipe['positive']]]
            cached=float(Decimal(result['value'])) if result['value'] is not None else 'n.a.'
            formula(build,row,i,f'=IF(AND({",".join(conditions)}),{expression},"n.a.")',cached,recipe['format'])

    title(overview,'年度财务分析'); write(overview,3,0,f'{model.company_id}  {years[0]}–{years[-1]}')
    write(overview,4,0,'系统校验通过，未经人工复核；金额为原币种基本单位，图表单位另列。' if automatic else '已人工确认；金额为原币种基本单位，图表单位另列。' if formal else '待人工审核：当前不生成正式分析数值和图表。')
    header(overview,6,['项目',*years]); overview.set_column(0,0,30); overview.set_column(1,max(4,len(years)),22)
    for j,metric in enumerate(['revenue','net_income','parent_net_income','assets','liabilities','cfo'],7):
        write(overview,j,0,INPUTS[metric][0])
        for i,year in enumerate(years,1):
            item=inputs[str(year)][metric]
            if formal: formula(overview,j,i,f"='分析计算'!{column_name(i)}{input_rows[metric]+1}",float(Decimal(item['value'])) if item['value'] is not None else 'n.a.')
            else: write(overview,j,i,'待审核')
    header(overview,14,['增长与财务比率',*years])
    for j,recipe in enumerate(recipes,15):
        write(overview,j,0,recipe['name'])
        for i,year in enumerate(years,1):
            result=results[year,recipe['name']]
            if formal: formula(overview,j,i,f"='分析计算'!{column_name(i)}{result_rows[recipe['name']]+1}",float(Decimal(result['value'])) if result['value'] is not None else 'n.a.',recipe['format'])
            else: write(overview,j,i,'待审核')
    cagr_row=16+len(recipes); write(overview,cagr_row,0,'营业收入 CAGR')
    if formal and analysis['cagr']['value'] is not None:
        last=column_name(len(years)); count=len(years)
        expression=f'=IF(AND(COUNT(B8:{last}8)={count},B8>0,{last}8>0),({last}8/B8)^(1/({years[-1]}-{years[0]}))-1,"n.a.")'
        formula(overview,cagr_row,1,expression,float(Decimal(analysis['cagr']['value'])),'percent')
    else: write(overview,cagr_row,1,'n.a.' if formal else '待审核')

    title(method,'方法与口径'); write(method,2,0,'数据版本'); write(method,2,1,payload['dataset_fingerprint'])
    method.set_column('A:A',29); method.set_column('B:B',64); method.set_column('C:C',85); method.set_column('D:D',46)
    for row,(label,note) in enumerate([
        ('口径','各年本年主列；比较数差异需明确采用 as_reported，不自动覆盖重述。'),
        ('单位','源表保留原披露单位；分析使用基本单位。不同币种不自动换汇。成本/资本支出按配置的正负口径转换为支出金额。'),
        ('校验方式' if automatic else '审核','系统自动来源与规则校验；无人工审核人或人工批准记录。' if automatic else '黄色区域可编辑；原始数据另列，修正须有理由。零是有效输入，MISSING 表示缺失。'),
        ('限制',' '.join(model.limitations).replace('比较栏差异必须人工明确接受','比较栏差异由系统按 as_reported 保留') if automatic else ' '.join(model.limitations))],4):
        write(method,row,0,label); write(method,row,1,note,'wrap'); method.set_row(row,38)
    header(method,9,['指标','公式','定义'])
    for row,recipe in enumerate(recipes,10):
        for col,val in enumerate([recipe['name'],recipe['expression'],recipe['definition']]): write(method,row,col,val,'wrap')
        method.set_row(row,34)
    row=12+len(recipes)
    for item in analysis['unavailable']:
        write(method,row,0,item['name']); write(method,row,1,item['reason'],'wrap'); method.set_row(row,34); row+=1
    row+=1; header(method,row,['跨报告比较差异','原报主列','后续报告比较栏','处理方式']); row+=1
    for conflict in model.conflicts:
        write(method,row,0,f'{conflict["value_year"]} {conflict["metric"]}')
        write(method,row,1,Decimal(conflict['current']),'amount'); write(method,row,2,Decimal(conflict['comparative']),'amount')
        write(method,row,3,'系统按 as_reported 保留各年原报主列。' if automatic else '人工确认 as_reported 后采用各年原报主列。','wrap'); method.set_row(row,34); row+=1
    row+=1; header(method,row,['年度','不可计算项目','具体原因']); row+=1
    missing=[(r['year'],r['name'],r['reason']) for r in analysis['results'] if r['value'] is None] if formal else [('全部年度','历史分析','来源报表待人工确认。')]
    if formal and analysis['cagr']['value'] is None: missing.append(('全期间','营业收入 CAGR',analysis['cagr']['reason']))
    for entry in missing:
        for col,item in enumerate(entry): write(method,row,col,item,'wrap')
        method.set_row(row,38); row+=1
    row+=1; header(method,row,['原报表自动勾稽','比较栏','结果 / 差额']); row+=1
    for statement in model.statements:
        for check in statement.checks:
            write(method,row,0,f'{statement.report_year}_{statement.kind} / {check["name"]}')
            write(method,row,1,statement.columns[check['column']].raw_header)
            write(method,row,2,f'{check["status"]} / {check.get("difference","n.a.")}'); row+=1

    if formal:
        specs=[('收入与利润',['revenue','net_income'],40,0,False),
               ('年度增长率',['营业收入同比','合并净利润同比'],40,4,True),
               ('盈利能力',['毛利率','净利率','ROE'],56,0,True),
               ('资产负债率',['资产负债率'],56,4,True),
               ('现金流',['cfo','简化自由现金流'],72,0,False)]
        helper=max(len(years)+3,10); currency=model.statements[0].currency or '原币种'
        for chart_title,metrics,chart_row,chart_col,is_percent in specs:
            amounts=[abs(float(Decimal(v))) for metric in metrics for year in years
                     if (v:=(inputs[str(year)][metric]['value'] if metric in INPUTS else results[year,metric]['value'])) is not None]
            maximum=max(amounts,default=0); divisor=1 if is_percent else 1e9 if maximum>=1e9 else 1e6 if maximum>=1e6 else 1
            unit=('十亿 ' if divisor==1e9 else '百万 ' if divisor==1e6 else '')+currency
            write(build,7,helper,'年度')
            for i,year in enumerate(years,8): write(build,i,helper,str(year))
            chart=workbook.add_chart({'type':'line'})
            for k,metric in enumerate(metrics,1):
                label=INPUTS[metric][0] if metric in INPUTS else metric; write(build,7,helper+k,label)
                for i,year in enumerate(years,8):
                    item=inputs[str(year)][metric] if metric in INPUTS else results[year,metric]
                    ref=f'{column_name(i-7)}{(input_rows.get(metric,result_rows.get(metric)))+1}'
                    if item['value'] is None: write(build,i,helper+k,None)
                    else: formula(build,i,helper+k,f'=IF(ISNUMBER({ref}),{ref}/{divisor},"")',float(Decimal(item['value']))/divisor)
                chart.add_series({'name':label,'categories':['分析计算',8,helper,7+len(years),helper],
                    'values':['分析计算',8,helper+k,7+len(years),helper+k],
                    'line':{'color':['#285B8C','#CC7438','#4F856A'][(k-1)%3],'width':2}})
            chart.set_title({'name':chart_title if is_percent else f'{chart_title}（{unit}）'})
            chart.set_legend({'position':'bottom'}); chart.set_y_axis({'num_format':'0%' if is_percent else '0.0'})
            chart.set_x_axis({'name':'年度'}); chart.show_blanks_as('gap'); chart.set_size({'width':620,'height':300})
            overview.insert_chart(chart_row,chart_col,chart,{'x_offset':4,'y_offset':8}); helper+=len(metrics)+2
    else: write(overview,40,0,'完成人工审核后生成五张趋势图。')
    workbook.close()
    output.parent.mkdir(parents=True,exist_ok=True)
    with output.open('xb') as stream: stream.write(buffer.getvalue())
    return output
